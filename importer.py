import csv, json
from typing import Iterable, Dict, Any
from storage import insert_feedback, insert_aspect_opinions, init_db
from aspects import ASPECTS

# -----------------------------------------------------------------------------
# load_long_csv
# -----------------------------------------------------------------------------
def load_long_csv(path: str) -> Iterable[Dict[str, Any]]:
    """
    Load long-form CSV files with row-level aspect annotations.

    Parameters
    ----------
    path : str
        Path to the long-form CSV dataset. Expected file format:
        reviews_multi_aspect_merged_long.csv

    Expected Columns
    ----------------
    - review_id : str
    - text      : str (non-empty)
    - aspect    : str (mapped to canonical ASPECTS; invalid → "OTHER")
    - sentiment : {"positive","negative","neutral"}
    - source    : annotation source (e.g., "gold", "auto")

    Returns
    -------
    Iterable[Dict[str, Any]]
        Yields dictionaries of the form:
            {
                "review_id": <str or None>,
                "text": <str>,
                "opinions": [
                    {"aspect": ..., "sentiment": ..., "score": 1.0, "source": ...},
                    ...
                ]
            }

    Notes
    -----
    - Multiple CSV rows with same review_id are grouped into a single record.
    - The manual grouping mechanism ensures compatibility with datasets that
      store each aspect-level annotation on a separate line.
    - Non-conforming or unlabeled rows are skipped.
    """
    buf: Dict[str, Dict[str, Any]] = {}

    with open(path, encoding="utf-8") as f:
        r = csv.DictReader(f)

        for row in r:
            rid = (row.get("review_id") or "").strip() or None
            text = (row.get("text") or "").strip()

            aspect = (row.get("aspect") or "").strip().upper() or "OTHER"
            sent = (row.get("sentiment") or "").strip().lower()
            source = (row.get("source") or "").strip().lower() or "gold"

            # Discard unlabeled or textless rows
            if not text or sent not in ("positive", "negative", "neutral"):
                continue

            # Normalize aspect label
            if aspect not in ASPECTS:
                aspect = "OTHER"

            # Use review_id as grouping key; fallback to generated key if missing
            key = rid or f"row_{len(buf)}"

            if key not in buf:
                buf[key] = {"review_id": rid, "text": text, "opinions": []}

            # Append aspect-level annotation
            buf[key]["opinions"].append({
                "aspect": aspect,
                "sentiment": sent,
                "score": 1.0,       # gold or CSV-based labels treated as full confidence
                "source": source
            })

    # Yield aggregated review-level structures
    for v in buf.values():
        yield v


# -----------------------------------------------------------------------------
# load_jsonl
# -----------------------------------------------------------------------------
def load_jsonl(path: str) -> Iterable[Dict[str, Any]]:
    """
    Load dataset from JSONL format.

    Parameters
    ----------
    path : str
        Path to JSON Lines file consisting of one JSON object per line.

    Returns
    -------
    Iterable[Dict[str, Any]]
        Each yielded object contains:
            - review_id
            - text
            - opinions (list of aspect-level annotations)

    Notes
    -----
    - Lines without valid text are skipped.
    - This format is frequently used for storing structured annotations
      generated by upstream NLP systems.
    """
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue

            obj = json.loads(line)
            text = obj.get("text", "").strip()

            if not text:
                continue

            opinions = obj.get("opinions") or []
            yield {
                "review_id": obj.get("review_id"),
                "text": text,
                "opinions": opinions
            }


# -----------------------------------------------------------------------------
# import_dataset
# -----------------------------------------------------------------------------
def import_dataset(path: str):
    """
    Import dataset into the system database.

    Parameters
    ----------
    path : str
        Path to either:
        - a JSONL file (".jsonl")
        - a long-form CSV file (default)

    Process
    -------
    1. Initialize database connection.
    2. Select loader based on file extension.
    3. For each data item:
         - Insert feedback text
         - Insert associated aspect-level opinions
    4. Print summary statistics.

    Notes
    -----
    - The loader abstracts away differences between granular (long CSV)
      and structured (JSONL) datasets.
    - Aspect-level annotations are stored in normalized form inside the DB.
    """
    init_db()

    # Choose file loader
    items: Iterable[Dict[str, Any]]
    if path.lower().endswith(".jsonl"):
        items = load_jsonl(path)
    else:
        items = load_long_csv(path)

    n_fb, n_op = 0, 0

    # Insert items into database
    for it in items:
        fid = insert_feedback(it["text"], review_id=it.get("review_id"))
        insert_aspect_opinions(fid, it["opinions"])

        n_fb += 1
        n_op += len(it["opinions"])

    print(f"[OK] imported {n_fb} feedback, {n_op} aspect-opinions from {path}")
