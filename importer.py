# This module provides dataset import utilities for the feedback analysis
# system. It supports two formats:
#   (1) Long-form CSV files with repeated rows per review_id, each containing
#       an aspect-level annotation.
#   (2) JSONL files containing free-form opinion lists.
#
# During import, the module normalizes aspect labels, aggregates annotations
# per review, and inserts the resulting entries into the system database.
