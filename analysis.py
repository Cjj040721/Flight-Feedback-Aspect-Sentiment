# This module provides utility functions for computing aspect-level sentiment
# statistics and formatting the results into a readable table. It is designed
# for processing annotated sentiment analysis datasets where each record
# contains an aspect label and an associated sentiment category.
# -----------------------------------------------------------------------------

from collections import Counter, defaultdict
from typing import Dict, Any, List

# Predefined sentiment categories used for validation and ordering.
LABELS = ("positive", "negative", "neutral")


def compute_aspect_stats(rows: List[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    """
    Compute sentiment distribution statistics for each aspect.

    Parameters
    ----------
    rows : List[Dict[str, Any]]
        A list of dictionaries, where each dictionary represents a data record
        containing at minimum the keys "aspect" and "sentiment".

    Returns
    -------
    Dict[str, Dict[str, Any]]
        A dictionary mapping each aspect to its computed statistics. For each
        aspect, the returned structure includes:
            - "counts": absolute counts of positive, negative, and neutral labels
            - "total": total number of sentiment-labeled instances
            - "ratios": percentage distribution (0.0–100.0) for each sentiment
              category, rounded to one decimal place

    Notes
    -----
    - If no aspect is provided in a record, it defaults to "OTHER".
    - Sentiment labels are normalized to lowercase before evaluation.
    - Only labels contained in LABELS are counted.
    """
    aspect_counts: Dict[str, Counter] = defaultdict(Counter)

    # Aggregate sentiment counts for each aspect
    for r in rows:
        aspect = r.get("aspect") or "OTHER"
        sentiment = (r.get("sentiment") or "").lower()
        if sentiment in LABELS:
            aspect_counts[aspect][sentiment] += 1

    stats: Dict[str, Dict[str, Any]] = {}

    # Compute total counts and ratios for each aspect
    for aspect, counter in aspect_counts.items():
        total = sum(counter.get(label, 0) for label in LABELS)

        # Compute sentiment ratios as percentages with one-decimal precision
        ratios = {
            label: (round(100.0 * counter.get(label, 0) / total, 1) if total else 0.0)
            for label in LABELS
        }

        stats[aspect] = {
            "counts": {label: int(counter.get(label, 0)) for label in LABELS},
            "total": int(total),
            "ratios": ratios
        }

    return stats


def pretty_table(stats: Dict[str, Dict[str, Any]]) -> str:
    """
    Format aspect-level sentiment statistics into a human-readable table.

    Parameters
    ----------
    stats : Dict[str, Dict[str, Any]]
        The output dictionary generated by `compute_aspect_stats`, containing
        counts and ratios for each aspect.

    Returns
    -------
    str
        A formatted string representing the statistics table. Columns include:
        Aspect, Total, Positive %, Negative %, Neutral %.

    Notes
    -----
    - Aspects are sorted in descending order by the number of total entries.
    - Column widths are pre-defined to maintain alignment in monospaced fonts.
    """
    headers = ["Aspect", "Total", "Positive", "Negative", "Neutral"]
    colw = [22, 7, 10, 10, 10]

    # Construct header row
    hdr = (
        headers[0].ljust(colw[0]) +
        headers[1].rjust(colw[1]) +
        headers[2].rjust(colw[2]) +
        headers[3].rjust(colw[3]) +
        headers[4].rjust(colw[4])
    )
    sep = "-" * (sum(colw))
    lines = [hdr, sep]

    # Add rows sorted by total count in descending order
    for aspect, data in sorted(stats.items(), key=lambda kv: kv[1]["total"], reverse=True):
        ratios = data["ratios"]
        line = (
            aspect.ljust(colw[0]) +
            f"{data['total']:>{colw[1]}}" +
            f"{ratios['positive']:>{colw[2]}.1f}%" +
            f"{ratios['negative']:>{colw[3]}.1f}%" +
            f"{ratios['neutral']:>{colw[4]}.1f}%"
        )
        lines.append(line)

    return "\n".join(lines)
